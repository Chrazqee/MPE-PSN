def build_cifar(root, cutout=False, use_cifar10=True, download=False):
    aug = [transforms.RandomCrop(32, padding=4), transforms.RandomHorizontalFlip()]
    aug.append(CIFAR10Policy())
    aug.append(transforms.ToTensor())
    if use_cifar10:
        aug.append(
            transforms.Normalize((0.4914, 0.4822, 0.4465), (0.2023, 0.1994, 0.2010)),
        )
        if cutout:
            aug.append(Cutout(n_holes=1, length=16))
        transform_train = transforms.Compose(aug)
        transform_test = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(
                (0.4914, 0.4822, 0.4465), (0.2023, 0.1994, 0.2010)),
        ])
        train_dataset = CIFAR10(root=root,
                                train=True, download=download, transform=transform_train)
        val_dataset = CIFAR10(root=root,
                              train=False, download=download, transform=transform_test)

    else:
        aug.append(
            transforms.Normalize(
                (0.5071, 0.4867, 0.4408), (0.2675, 0.2565, 0.2761)),
        )
        if cutout:
            aug.append(Cutout(n_holes=1, length=8))
        transform_train = transforms.Compose(aug)
        transform_test = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(
                (0.5071, 0.4867, 0.4408), (0.2675, 0.2565, 0.2761)),
        ])
        train_dataset = CIFAR100(root=root,
                                 train=True, download=download, transform=transform_train)
        val_dataset = CIFAR100(root=root,
                               train=False, download=download, transform=transform_test)

    return train_dataset, val_dataset

